/**
 * Builds src/components/brand/brand-icons.ts: a tiny map with only the brand logos the page
 * uses, so no icon library ships to the browser.
 *
 * Sources (all permissive):
 * - Iconify "logos" set by Gil Barbara (CC0-1.0): full-colour official marks.
 * - Iconify "vscode-icons" (MIT): Microsoft Outlook / Excel marks.
 * - Simple Icons (CC0-1.0): single-colour marks with the brand's official hex.
 *
 * Run: node scripts/build-brand-icons.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { getIconData, iconToSVG } from "@iconify/utils";
import * as si from "simple-icons";

const require = createRequire(import.meta.url);
const logos = JSON.parse(readFileSync(require.resolve("@iconify-json/logos/icons.json"), "utf8"));
const vscode = JSON.parse(
  readFileSync(require.resolve("@iconify-json/vscode-icons/icons.json"), "utf8"),
);

function iconify(set, name) {
  const data = getIconData(set, name);
  if (!data) throw new Error(`missing ${set.prefix}:${name}`);
  const { attributes, body } = iconToSVG(data);
  // Prefix ids so gradients from different logos never collide.
  const safe = body
    .replace(/id="([^"]+)"/g, `id="${name}-$1"`)
    .replace(/url\(#([^)]+)\)/g, `url(#${name}-$1)`)
    .replace(/href="#([^"]+)"/g, `href="#${name}-$1"`);
  return { viewBox: attributes.viewBox, body: safe };
}

function simple(key) {
  // biome-ignore lint/performance/noDynamicNamespaceImportAccess: build script, runs once.
  const icon = si[key];
  if (!icon) throw new Error(`missing simple-icons ${key}`);
  return { viewBox: "0 0 24 24", body: `<path fill="#${icon.hex}" d="${icon.path}"/>` };
}

const ICONS = {
  whatsapp: ["WhatsApp", iconify(logos, "whatsapp-icon")],
  gmail: ["Gmail", iconify(logos, "google-gmail")],
  googleCalendar: ["Google Calendar", iconify(logos, "google-calendar")],
  googleSheets: ["Google Sheets", simple("siGooglesheets")],
  googleDrive: ["Google Drive", iconify(logos, "google-drive")],
  google: ["Google", iconify(logos, "google-icon")],
  outlook: ["Outlook", iconify(vscode, "file-type-outlook")],
  excel: ["Excel", iconify(vscode, "file-type-excel")],
  teams: ["Microsoft Teams", iconify(logos, "microsoft-teams")],
  slack: ["Slack", iconify(logos, "slack-icon")],
  notion: ["Notion", iconify(logos, "notion-icon")],
  openai: ["OpenAI", iconify(logos, "openai-icon")],
  stripe: ["Stripe", simple("siStripe")],
  hubspot: ["HubSpot", simple("siHubspot")],
  shopify: ["Shopify", simple("siShopify")],
  calendly: ["Calendly", simple("siCalendly")],
  woocommerce: ["WooCommerce", iconify(logos, "woocommerce-icon")],
};

// Gradients and other <defs> are hoisted into one always-rendered sprite. If they stayed
// inside each icon, an icon hidden with display:none would take its gradient with it and
// every other copy of that logo would lose its colour.
const defs = [];
const lines = Object.entries(ICONS).map(([key, [label, { viewBox, body }]]) => {
  const stripped = body.replace(/<defs>([\s\S]*?)<\/defs>/g, (_, inner) => {
    defs.push(inner);
    return "";
  });
  return `  ${key}: { label: ${JSON.stringify(label)}, viewBox: ${JSON.stringify(viewBox)}, body: ${JSON.stringify(stripped)} },`;
});
const out = `// Generated by scripts/build-brand-icons.mjs. Do not edit by hand.
// Logos are trademarks of their owners, shown to indicate integrations.
// Sources: Iconify "logos" (CC0), Iconify "vscode-icons" (MIT), Simple Icons (CC0).

export const BRAND_ICONS = {
${lines.join("\n")}
} as const;

export type Brand = keyof typeof BRAND_ICONS;

/** Shared gradient definitions for the logos above; render once per page. */
export const BRAND_DEFS = ${JSON.stringify(defs.join(""))};
`;
writeFileSync(new URL("../src/components/brand/brand-icons.ts", import.meta.url), out);
console.log(`wrote ${Object.keys(ICONS).length} icons, ${Math.round(out.length / 1024)} KB`);
